out = []
by_bone = {}
for pid, code, x, m in S:
    assert pid in POS, ("no position", pid)
    assert code in TA, ("unknown TA code", code)
    p = POS[pid]
    lat, ru, flag = TA[code]
    lat = lat.split(";")[0].strip()
    rec = {"b": p["b"], "id": pid, "t": "ta", "c": code, "ru": ru, "lat": lat, "x": x, "p": p["p"], "n": p["n"],
           "m": [[a, r, c] if c else [a, r] for a, r, c in m]}
    if code in TG:
        rec["g"] = TG[code]
    if flag == "inc":
        rec["inc"] = 1
    if flag == "part":
        rec["part"] = 1
    by_bone.setdefault(p["b"], []).append(code)
    out.append(rec)
for old, ru, x, m in A:
    src = POS.get(old) or OLD.get(old)
    assert src, ("no position", old)
    out.append({"b": src["b"], "id": old, "t": "att", "ru": ru, "lat": "", "x": x, "p": src["p"], "n": src["n"],
                "m": [[a, r, c] if c else [a, r] for a, r, c in m]})

# every modelled bone shows exactly its official list
leg_bones = {p["b"] for p in POS.values()} | {"cuneiform_med", "cuneiform_int", "cuneiform_lat", "sesamoid_pedis"}
for b in leg_bones:
    want, got = sorted(BONE[b]), sorted(by_bone.get(b, []))
    assert want == got, (b, sorted(set(want) - set(got)), sorted(set(got) - set(want)))
ids = [o["id"] for o in out]
assert len(ids) == len(set(ids)), "duplicate ids"
unused = set(POS) - {s[0] for s in S} - {a[0] for a in A}
