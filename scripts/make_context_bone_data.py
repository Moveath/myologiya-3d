"""Publish former context as selectable bones, without invented landmark positions."""
from pathlib import Path
import json
from collections import Counter
from ta98 import T, BONE
from lumbar_terms import BONES, BONE_CODES, description_for, WHOLE_TERMS, DESCRIPTIONS, APPLICABILITY_NOTE
from context_bone_cards import CONTEXT_BONE_CARDS, catalogue_entries

ROOT=Path(__file__).resolve().parents[1]
def dump(value): return json.dumps(value,ensure_ascii=False,indent=2)
cards={**CONTEXT_BONE_CARDS,**BONES}
for i in range(1,6):
    cards[f'lumbar_{i}']={**cards[f'lumbar_{i}'],'sourceId':f'FMA{13071+i}',
        'termScopeNote':APPLICABILITY_NOTE,
        'note':cards[f'lumbar_{i}']['note']+' Кость имеет собственную исходную модель. Координаты образований отдельно не проверены; мышцы поясницы в этом дополнении не заявляются.'}
for card in cards.values():
    assert len({r['url'].split('#')[0] for r in card['refs']})>=2
pins=[]
for bone,codes in BONE_CODES.items():
    for code in codes:
        desc=description_for(bone,code)
        assert len({r['url'].split('#')[0] for r in desc['refs']})>=2,(bone,code)
        pins.append(dict(b=bone,id='context_'+bone+'_'+code.replace('.','_'),t='ta',c=code,
            ru=T[code][1],lat=T[code][0],x=desc['x']+' '+desc.get('note',''),refs=desc['refs'],
            p=None,n=None,m=[],modelNote='Название и описание проверены по источникам. Положение на этой сетке отдельно не проверено; точка не добавлена.'))
for bone,entries in catalogue_entries().items():
    for entry in entries:
        code=entry['c']
        pins.append(dict(**entry,b=bone,id='context_'+bone+'_'+code.replace('.','_'),t='ta',m=[],
            x='Термин каталога TA98. Координаты и форма образования на левом экземпляре отдельно не проверены. Разметка правой стороны не переносилась.',
            refs=[dict(title='IFAA — Terminologia Anatomica (TA98)',url='https://ifaa.unifr.ch/Public/TNAEntryPage/auto/TA98/LAEN/TAH'+('1027' if bone=='hip_bone_left' else '894')+'%20A2F%20EN.htm',locator=code)],
            **({'inc':1} if T[code][2]=='inc' else {})))
for bone in cards:
    assert Counter(p['c'] for p in pins if p['b']==bone)==Counter(BONE[bone])
sources={b:{'sourceId':d['sourceId'],'sec':d['sec']} for b,d in cards.items()}
whole=[dict(c=c,ru=T[c][1],lat=T[c][0],**DESCRIPTIONS[c]) for c in WHOLE_TERMS]
(ROOT/'site/data-context-bones.js').write_text('/* Generated by scripts/make_context_bone_data.py. */\n'+
    'window.ATLAS.boneGroups.push({id:"b_lumbar",title:"Поясничные позвонки",sec:"leg"});\n'+
    'Object.assign(window.ATLAS.bones,'+dump(cards)+');\n'+
    'window.ATLAS.contextBoneSources='+dump(sources)+';\n'+
    'window.ATLAS.lumbarWholeTerms='+dump(whole)+';\n',encoding='utf8')
(ROOT/'site/pins-context-bones.js').write_text('/* Generated by scripts/make_context_bone_data.py. No landmark coordinates. */\nwindow.ATLAS.pins.push(...'+dump(pins)+');\n',encoding='utf8')
audit=json.loads((ROOT/'research/context-ownership-audit.json').read_text(encoding='utf8'))
audit['resolution']=dict(stage='published_supplement',bones={b:dict(section=d['sec'],subsection=d['sub'],sourceId=d['sourceId']) for b,d in cards.items()},contextOnlyBonesRemaining=0,
    note='All nine formerly context-only bone instances have selectable owners. Non-bone context and future body scope are unchanged. Positions remain unverified.')
(ROOT/'research/context-ownership-audit.json').write_text(dump(audit)+'\n',encoding='utf8')
print(f'{len(cards)} selectable bones; {len(pins)} catalogue entries without coordinates; {len(whole)} whole-region terms')
