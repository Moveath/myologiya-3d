"""Generate head cards from reviewed editorial source modules."""
from copy import deepcopy
from pathlib import Path
import json
import manifest_head as manifest
from head_terms import BONES
from head_muscles import MUSCLE_TEMPLATES

root = Path(__file__).resolve().parents[1]
groups = [
    {'id':'head_scalp','title':'Мышцы свода черепа','region':'mimetic','sec':'head'},
    {'id':'head_face','title':'Мимические мышцы лица','region':'mimetic','sec':'head'},
    {'id':'head_ear','title':'Мышцы ушной раковины','region':'mimetic','sec':'head'},
    {'id':'head_mastication','title':'Жевательные мышцы','region':'mastication','sec':'head'},
]
bone_groups = [
    {'id':'head_neurocranium','title':'Мозговой череп','sec':'head'},
    {'id':'head_viscerocranium','title':'Лицевой череп','sec':'head'},
    {'id':'b_soft_head','title':'Апоневрозы головы','sec':'head'},
]
cranial = {'frontal','parietal','occipital','temporal','sphenoid','ethmoid'}
bones = {}
for key in manifest.BONES:
    base = key.removesuffix('_right').removesuffix('_left')
    record = deepcopy(BONES[base])
    if key.endswith(('_right','_left')):
        record['ru'] += ' · ' + ('правая' if key.endswith('_right') else 'левая')
    record['sub'] = 'neurocranium' if base in cranial else 'viscerocranium'
    record['g'] = 'head_' + record['sub']
    record['v'] = 'med' if key.endswith('_left') else 'antlat'
    bones[key] = record
bones['epicranial_aponeurosis'] = {
    'ru':'Сухожильный шлем', 'lat':'galea aponeurotica; aponeurosis epicranialis',
    'g':'b_soft_head', 'sub':'mimetic',
    'x':'Апоневроз надчерепной мышцы. Его положение показано исходной моделью BodyParts3D.',
    'refs':[
        {'title':'TA98: мышцы головы','url':'https://ifaa.unifr.ch/Public/TNAEntryPage/auto/TA98/LAEN/TAH1673%20A2F%20EN.htm'},
        {'title':'BodyParts3D','url':'https://dbarchive.biosciencedbc.jp/en/bodyparts3d/'},
    ],
}
muscles = {}
for base, source in MUSCLE_TEMPLATES.items():
    keys = [base] if base in ('orbicularis_oris','transversus_menti') else [base+'_right',base+'_left']
    for key in keys:
        record = deepcopy(source)
        if key.endswith(('_right','_left')):
            record['ru'] += ' · ' + ('правая' if key.endswith('_right') else 'левая')
        if key.endswith('_left'):
            record['v'] = {'lat':'med','antlat':'antmed','postlat':'medpost'}.get(record.get('v'), record.get('v','ant'))
        record['noModel'] = key not in manifest.MUSCLES
        available = {part for _, part in manifest.MUSCLES.get(key, [])}
        for part, data in record.get('parts', {}).items():
            if part not in available: data['noModel'] = True
        muscles[key] = record
assert set(manifest.MUSCLES) <= set(muscles), set(manifest.MUSCLES)-set(muscles)
assert all(m['g'] in {g['id'] for g in groups} for m in muscles.values())
text = ('/* Generated by scripts/make_head_data.py; edit the reviewed source modules. */\n'
        '(function(A){\nA.groups.push(...'+json.dumps(groups,ensure_ascii=False)+');\n'
        'A.boneGroups.push(...'+json.dumps(bone_groups,ensure_ascii=False)+');\n'
        'Object.assign(A.muscles,'+json.dumps(muscles,ensure_ascii=False,indent=2)+');\n'
        'Object.assign(A.bones,'+json.dumps(bones,ensure_ascii=False,indent=2)+');\n})(window.ATLAS);\n')
(root/'site/data-head.js').write_text(text,encoding='utf-8')
print(len(manifest.BONES),'bones;',len(muscles),'muscle cards;',len(manifest.MUSCLES),'modeled muscle instances')
