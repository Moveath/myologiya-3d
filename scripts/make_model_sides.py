"""Technical visibility metadata from existing model manifests, never coordinates."""
import importlib
import json
import re
from pathlib import Path
from context_bone_cards import CONTEXT_BONE_CARDS

ROOT = Path(__file__).resolve().parents[1]


def build():
    names = dict(line.split('\t', 1) for line in (ROOT/'bp/all_named.tsv').read_text(encoding='utf-8').splitlines())
    def side(ids):
        # No side word means an unseparated source, not proof of a midline structure.
        sides = {s for id in ids for s in re.findall(r'\b(right|left)\b', names[id])}
        return next(iter(sides)) if len(sides) == 1 else 'unseparated'
    result = {}
    for section, module in [('arm','manifest'),('leg','manifest_leg'),('head','manifest_head'),('neck','manifest_neck'),('trunk','manifest_thorax')]:
        manifest = importlib.import_module(module)
        rows = {}
        for kind in ('MUSCLES','BONES','OTHER'):
            for id, sources in getattr(manifest, kind, {}).items():
                rows[id] = side([s[0] if isinstance(s, tuple) else s for s in sources])
        for source in manifest.CONTEXT:
            rows['context:'+source] = side([source])
        for id, card in CONTEXT_BONE_CARDS.items():
            if card['sec'] == section:
                rows[id] = side([card['sourceId']])
        result[section] = rows
    return result


if __name__ == '__main__':
    result = build()
    target = ROOT/'site/atlas-model-sides.js'
    target.write_text('// Generated by scripts/make_model_sides.py from manifests and bp/all_named.tsv.\n'
                      'export const MODEL_SIDES = '+json.dumps(result, ensure_ascii=False, indent=2)+';\n', encoding='utf-8')
    print(f'Model side metadata: {sum(map(len,result.values()))} identities; no model/data changes')
