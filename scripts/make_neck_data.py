"""Generate neck cards from the reviewed source modules, not from mesh names."""
from copy import deepcopy
from pathlib import Path
import json
import manifest_neck as manifest
from neck_muscles import MUSCLE_TEMPLATES
from neck_terms import BONES, APPLICABILITY_NOTE

ROOT = Path(__file__).resolve().parents[1]
groups = [
    {'id':'neck_superficial','title':'Поверхностные мышцы шеи','region':'superficial','sec':'neck'},
    {'id':'neck_suprahyoid','title':'Надподъязычные мышцы','region':'hyoid','sec':'neck'},
    {'id':'neck_infrahyoid','title':'Подподъязычные мышцы','region':'hyoid','sec':'neck'},
    {'id':'neck_prevertebral','title':'Предпозвоночные мышцы','region':'deep','sec':'neck'},
    {'id':'neck_scalene','title':'Лестничные мышцы','region':'deep','sec':'neck'},
    {'id':'neck_suboccipital','title':'Подзатылочные мышцы','region':'posterior','sec':'neck'},
    {'id':'neck_posterior','title':'Задние мышцы шеи','region':'posterior','sec':'neck'},
    {'id':'neck_girdle','title':'Мышцы, связывающие шею с плечевым поясом','region':'girdle','sec':'neck'},
]
bone_groups = [
    {'id':'neck_vertebrae','title':'Шейные позвонки','sec':'neck'},
    {'id':'neck_hyoid','title':'Подъязычная кость','sec':'neck'},
]
bones = {}
for key in manifest.BONES:
    record = deepcopy(BONES[key])
    if key != 'hyoid':
        record['termScopeNote'] = APPLICABILITY_NOTE
    record.update(g='neck_hyoid' if key=='hyoid' else 'neck_vertebrae',
                  sub='hyoid' if key=='hyoid' else 'cervical', v='antlat')
    bones[key] = record
muscles = {}
for base, source in MUSCLE_TEMPLATES.items():
    for side in ('right','left'):
        key = f'{base}_{side}'
        record = deepcopy(source)
        record['ru'] += ' · '+('правая' if side=='right' else 'левая')
        if side=='left':
            record['v'] = {'lat':'med','antlat':'antmed','postlat':'medpost'}.get(record.get('v'),record.get('v','ant'))
        if base.startswith('neck_'):
            record['g'] = 'neck_girdle'
        record['noModel'] = key not in manifest.MUSCLES
        available = {part for _,part in manifest.MUSCLES.get(key,[])}
        for part,data in record.get('parts',{}).items():
            data['noModel'] = part not in available
        muscles[key] = record
assert set(muscles)==set(manifest.MUSCLES), (set(manifest.MUSCLES)-set(muscles),set(muscles)-set(manifest.MUSCLES))
assert all(m['g'] in {g['id'] for g in groups} for m in muscles.values())
assert all(part in muscles[key].get('parts',{}) for key,parts in manifest.MUSCLES.items() for _,part in parts if part)
text = ('/* Generated by scripts/make_neck_data.py; edit reviewed source modules. */\n'
        '(function(A){\nA.groups.push(...'+json.dumps(groups,ensure_ascii=False)+');\n'
        'A.boneGroups.push(...'+json.dumps(bone_groups,ensure_ascii=False)+');\n'
        'Object.assign(A.muscles,'+json.dumps(muscles,ensure_ascii=False,indent=2)+');\n'
        'Object.assign(A.bones,'+json.dumps(bones,ensure_ascii=False,indent=2)+');\n})(window.ATLAS);\n')
(ROOT/'site/data-neck.js').write_text(text,encoding='utf-8')
print(len(bones),'bones;',len(muscles),'muscle cards;',sum(bool(part) for parts in manifest.MUSCLES.values() for _,part in parts),'separate source parts')
