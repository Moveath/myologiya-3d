# ======================= сборка и проверка =======================
CARPALS = ["scaphoid", "lunate", "triquetrum", "pisiform", "trapezium", "trapezoid", "capitate", "hamate"]
out, by_bone = [], {}
for pid, code, x, m in S:
    assert pid in POS, ("no position", pid)
    assert code in TA, ("unknown TA code", code)
    p = POS[pid]
    lat, ru, flag = TA[code]
    rec = {"b": p["b"], "id": pid, "t": "ta", "c": code, "ru": ru, "lat": lat.split(";")[0].strip(), "x": x, "p": p["p"], "n": p["n"],
           "m": [[a, r, c] if c else [a, r] for a, r, c in m]}
    if code in TG:
        rec["g"] = TG[code]
    if flag == "inc":
        rec["inc"] = 1
    if code in CARPUS_SHARED:
        rec["sh"] = CARPALS  # belongs to the carpus as a whole
    else:
        by_bone.setdefault(p["b"], []).append(code)
    out.append(rec)
for pid, ru, x, m, kind, lat in A:
    src = POS.get(pid) or OLD.get(pid)
    assert src, ("no position", pid)
    out.append({"b": src["b"], "id": pid, "t": kind, "ru": ru, "lat": lat, "x": x, "p": src["p"], "n": src["n"],
                "m": [[a, r, c] if c else [a, r] for a, r, c in m]})

arm_bones = [b for b in BONE if b in {p["b"] for p in OLD.values()} | set(CARPALS)]
for b in arm_bones:
    want, got = sorted(BONE[b]), sorted(by_bone.get(b, []))
    assert want == got, (b, sorted(set(want) - set(got)), sorted(set(got) - set(want)))
ids = [o["id"] for o in out]
assert len(ids) == len(set(ids)), "duplicate ids"
unused = set(POS) - {s[0] for s in S} - {a[0] for a in A}
assert not unused, ("positions without description", unused)

