"""Generate source-reviewed supplementary cards without altering TA98 or GLB."""
import json
from pathlib import Path
from head_skull_batch7 import additional_records as batch7_records
from head_skull_batch8 import additional_records as batch8_records
from head_skull_final import additional_records as final_records
from skull_targeted_review import additional_records as targeted_records

records = list(batch7_records()) + list(batch8_records()) + list(final_records()) + list(targeted_records())
assert len(records)==79 and len({p['id'] for p in records})==len(records)
for row in records:
    assert not {'c', 'p', 'n', 'noModel'} & row.keys()
    assert len({r['authorGroup'] for r in row['refs']})>=2
root = Path(__file__).resolve().parents[1]
(root/'site/pins-head-extra.js').write_text(
    '/* Generated by scripts/make_pins_head_extra.py. */\nwindow.ATLAS.pins.push(...'+
    json.dumps(records,ensure_ascii=False,separators=(',',':'))+');\n',encoding='utf-8')
print(len(records),'supplementary cards; 0 coordinates; TA98 unchanged')
