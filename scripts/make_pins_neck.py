"""Neck TA98 catalogue plus independently inspected source markers.

Uninspected coordinates stay null. A catalogue entry does not assert a marker
or complete geometry. Common vertebral terms use documented applicability.
"""
from pathlib import Path
import json
from collections import Counter
import argparse
from neck_terms import T, BONE_CODES, description_for, WHOLE_TERMS, DESCRIPTIONS
from neck_stage5_review import review, additional_records
from neck_geometry_requirements import annotate_unlocated
from evidence_output import write_report

parser=argparse.ArgumentParser()
parser.add_argument('--report', help='New JSON path within an allocated evidence run')
args=parser.parse_args()

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'pins_neck/ta.json'
locations=json.loads(source.read_text(encoding='utf-8')) if source.exists() else []
if isinstance(locations,dict):
    locations=locations.get('records',locations.get('points',locations.get('pins',[])))
position={}
for row in locations:
    key=(row.get('b',row.get('bone')),row.get('c',row.get('code')))
    assert key not in position, ('Duplicate neck landmark',key)
    assert key[1] in BONE_CODES[key[0]], ('Unknown neck term',key)
    position[key]=row
pins=[]
for bone,codes in BONE_CODES.items():
    assert len(set(codes))==len(codes),bone
    for code in codes:
        description=description_for(bone,code)
        refs=description['refs']
        assert len({r['url'].split('#')[0] for r in refs})>=2,(bone,code,'two sources required')
        row=position.get((bone,code),{})
        p=row.get('p')
        pin=dict(b=bone,id='neck_'+bone+'_'+code.replace('.','_'),t='ta',c=code,
                 ru=T[code][1],lat=T[code][0],x=description['x'],p=p,n=row.get('n'),m=[],
                 refs=refs,
                 modelNote=row.get('modelNote') or 'Положение этого образования на данной сетке ещё не проверено. Карточка объясняет анатомию; произвольная точка или реконструкция не добавлены.')
        if description.get('note'):
            pin['x']+=' '+description['note']
        if p:
            pin['loc']=row.get('localization',row.get('loc'))
            assert pin['loc'] in ('surface','projection','internal','variant'), (bone,code)
            assert row.get('evidence'),(bone,code,'missing geometric provenance')
        if description.get('inc'):pin['inc']=1
        if T[code][2]=='ta_parentheses':pin['taParen']=True
        if row.get('secondaryMarkers'):pin['secondaryMarkers']=row['secondaryMarkers']
        pins.append(annotate_unlocated(review(pin)))
for bone,codes in BONE_CODES.items():
    assert Counter(p['c'] for p in pins if p['b']==bone)==Counter(codes)
whole=[dict(c=c,ru=T[c][1],lat=T[c][0],**DESCRIPTIONS[c]) for c in WHOLE_TERMS]
for term,kind in zip(whole,['volume','line','space','space']):
    term['geometryKind']=kind
    term['geometryReview']=dict(status='concept_only',coordinateAcceptance=False,extentAcceptance=False)
extras=[annotate_unlocated(p) for p in additional_records()]
(ROOT/'site/pins-neck.js').write_text('/* Generated by scripts/make_pins_neck.py. */\n'+
    'window.ATLAS.pins.push(...'+json.dumps(pins+extras,ensure_ascii=False,indent=2)+');\n'+
    'window.ATLAS.neckWholeTerms='+json.dumps(whole,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
report=dict(bones=len(BONE_CODES),catalogueEntries=len(pins),located=sum(bool(p['p']) for p in pins),
    unlocated=sum(not p['p'] for p in pins),wholeTerms=len(whole),
    additionalEntries=len(extras),geometryKinds=dict(Counter(p['geometryKind'] for p in pins)),
    fullGeometryClaim=False,independentAnatomicalAcceptance=False,
    byBone={b:dict(entries=len(c),located=sum(bool(p['p']) for p in pins if p['b']==b)) for b,c in BONE_CODES.items()})
report_path=write_report(report,'neck-coverage','neck-coverage.json',args.report)
print('Evidence:',report_path)
print(json.dumps(report,ensure_ascii=False))
