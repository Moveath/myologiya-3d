"""Thorax TA98 catalogue plus independently inspected source markers.

Uninspected coordinates stay null. A catalogue entry does not assert a marker
or complete geometry. Common vertebral terms use documented applicability.
"""
from pathlib import Path
import json
import argparse
from collections import Counter
from thorax_terms import T, BONE_CODES, description_for, WHOLE_TERMS, DESCRIPTIONS, TA_PAREN
from thorax_stage5_review import review, additional_records
from thorax_ribs_stage5 import review as review_ribs, additional_records as rib_additional_records
from evidence_output import write_report

parser=argparse.ArgumentParser()
parser.add_argument('--report',help='New JSON path within an allocated evidence run')
args=parser.parse_args()

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'pins_thorax/ta.json'
locations=json.loads(source.read_text(encoding='utf-8')) if source.exists() else []
if isinstance(locations,dict):
    locations=locations.get('records',locations.get('points',locations.get('pins',[])))
position={}
for row in locations:
    key=(row.get('b',row.get('bone')),row.get('c',row.get('code')))
    assert key not in position, ('Duplicate thorax landmark',key)
    assert key[1] in BONE_CODES[key[0]], ('Unknown thorax term',key)
    position[key]=row
pins=[]
for bone,codes in BONE_CODES.items():
    assert len(set(codes))==len(codes),bone
    for code in codes:
        description=description_for(bone,code)
        refs=description['refs']
        assert len({r['url'].split('#')[0] for r in refs})>=2,(bone,code,'two sources required')
        row=position.get((bone,code),{})
        p=row.get('p')
        pin=dict(b=bone,id='thorax_'+bone+'_'+code.replace('.','_'),t='ta',c=code,
                 ru=T[code][1],lat=T[code][0],x=description['x'],p=p,n=row.get('n'),m=[],
                 refs=refs,
                 modelNote=row.get('modelNote') or 'Положение этого образования на данной сетке ещё не проверено. Карточка объясняет анатомию; произвольная точка или реконструкция не добавлены.')
        if description.get('note'):
            pin['x']+=' '+description['note']
        for field in ('anatomyVerification','evidenceScope'):
            if description.get(field):pin[field]=description[field]
        if p:
            pin['loc']=row.get('localization',row.get('loc'))
            assert pin['loc'] in ('surface','projection','internal','variant'), (bone,code)
            assert row.get('evidence'),(bone,code,'missing geometric provenance')
        if description.get('inc'):pin['inc']=1
        if code in TA_PAREN:pin['taParen']=True
        if row.get('secondaryMarkers'):pin['secondaryMarkers']=row['secondaryMarkers']
        pins.append(review_ribs(review(pin)))
for bone,codes in BONE_CODES.items():
    assert Counter(p['c'] for p in pins if p['b']==bone)==Counter(codes)
whole=[dict(c=c,ru=T[c][1],lat=T[c][0],**DESCRIPTIONS[c]) for c in WHOLE_TERMS]
pins.extend(additional_records())
pins.extend(rib_additional_records())
(ROOT/'site/pins-thorax.js').write_text('/* Generated by scripts/make_pins_thorax.py. */\n'+
    'window.ATLAS.pins.push(...'+json.dumps(pins,ensure_ascii=False,indent=2)+');\n'+
    'window.ATLAS.thoraxWholeTerms='+json.dumps(whole,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
report=dict(bones=len(BONE_CODES),catalogueEntries=len(pins),located=sum(bool(p.get('p')) for p in pins),
    unlocated=sum(not p.get('p') for p in pins),wholeTerms=len(whole),
    fullGeometryClaim=False,independentAnatomicalAcceptance=False,
    byBone={b:dict(entries=sum(p['b']==b for p in pins),located=sum(bool(p.get('p')) for p in pins if p['b']==b)) for b in BONE_CODES})
print('Evidence:',write_report(report,'thorax-coverage','thorax-coverage.json',args.report))
print(json.dumps(report,ensure_ascii=False))
