"""Publish per-feature extent review without changing marker localization."""
from collections import Counter
from copy import deepcopy
from pathlib import Path
import hashlib
import json
from head_localization import positions
from head_terms import BONES
from ta98 import T

ROOT=Path(__file__).resolve().parents[1]
expected=positions()
native=json.loads((ROOT/'site/skull-native-features.json').read_text(encoding='utf8'))['markers']
rows=[];seen=set();sources=[]
for region in ('face','cranial','temporal'):
    path=ROOT/f'research/{region}-feature-extent-review.json'
    report=json.loads(path.read_text(encoding='utf8'))
    sources.append(dict(file=str(path.relative_to(ROOT)),sha256=hashlib.sha256(path.read_bytes()).hexdigest()))
    for item in report['rows']:
        bone,code=item['bone'],item['code'];key=(bone,code)
        assert key in expected and key not in seen,key;seen.add(key)
        assert item['originalLocalization']==expected[key]['localization'],key
        assert item['bestStatus'] in ('complete','partial','not_demonstrated','not_inspected'),key
        assert bool(item['completeFeatureGeometry'])==(item['bestStatus']=='complete'),key
        assert len(item['refs'])>=2 and all(r.get('locator') for r in item['refs']),key
        base=bone.removesuffix('_right').removesuffix('_left')
        bone_ru=BONES[base]['ru']+(' · справа' if bone.endswith('_right') else ' · слева' if bone.endswith('_left') else '')
        assessments=[]
        for assessment in item['assessments']:
            for view in assessment.get('views',[]):
                image=ROOT/view['screenshot']
                digest=view.get('sha256') or view.get('screenshotSha256')
                assert digest,view
                if image.exists():assert hashlib.sha256(image.read_bytes()).hexdigest()==digest,image
            viewer=deepcopy(assessment.get('viewer'))
            if viewer:
                assert viewer['mode'] in ('main','z','openear','microct','channels','cranial_channels'),viewer
                if viewer.get('marker'):
                    marker=next(p for p in native[viewer['mode']] if p['id']==viewer['marker'])
                    assert marker['b']==viewer['part'],viewer
                    # A marker-centred camera stays in its own source coordinates.
                    viewer['view'].setdefault('target',marker['p'])
            public={k:assessment.get(k) for k in ('source','status','confirmedExtent','limitations','viewer')}
            public['viewer']=viewer
            source_titles={'bp':'BodyParts3D 3.0','z':'Z-Anatomy','halle':'Halle, микро-КТ','openear':'OpenEar'}
            public['source']=report.get('sources',{}).get(assessment['source'],{}).get('title',source_titles.get(assessment['source'],assessment['source']))
            assessments.append(public)
        rows.append(dict(id=f'{bone}:{code}',bone=bone,boneRu=bone_ru,c=code,ru=T[code][1],lat=T[code][0],pinId='head_'+bone+'_'+code.replace('.','_'),localization=item['originalLocalization'],criterion=item['requiredExtent']['criterion'],status=item['bestStatus'],completeFeatureGeometry=item['completeFeatureGeometry'],assessments=assessments,refs=item['refs']))
assert seen==set(expected),(set(expected)-seen,seen-set(expected))
rows.sort(key=lambda r:(r['bone'],r['c']))
data=dict(version=1,total=len(rows),counts=dict(Counter(r['status'] for r in rows)),scope='macroscopic_source_feature_extent',independentExpertValidation=False,completeSkullGeometry=False,sourceReports=sources,rows=rows)
(ROOT/'site/skull-geometry-review.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf8')
index={r['id']:r['status'] for r in rows}
(ROOT/'site/skull-geometry-index.js').write_text('/* Generated by scripts/make_skull_geometry_review.py */\nwindow.ATLAS.headGeometry='+json.dumps(index,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
print('Full extent inventory:',len(rows),data['counts'],'; original pin states unchanged')
