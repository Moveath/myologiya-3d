"""Publish reviewed thoracic cards; source geometry and anatomy stay separate."""
from copy import deepcopy
from pathlib import Path
import json
import manifest_thorax as manifest
from thorax_muscles import MUSCLE_TEMPLATES, SIDED_TEMPLATES
from thorax_terms import BONES, APPLICABILITY_NOTE, THORAX_SOFT

ROOT=Path(__file__).resolve().parents[1]
groups=[dict(id='thorax_'+key,title=title,region=region,sec='trunk') for key,title,region in [
    ('pectoral','Мышцы, связывающие грудную клетку с верхней конечностью','pectoral'),
    ('wall','Собственные мышцы грудной стенки','wall'),
    ('diaphragm','Диафрагма','diaphragm'),
    ('back','Поверхностные мышцы спины','back'),
    ('deep_back','Глубокие мышцы спины','deepback'),
]]
bone_groups=[dict(id='thorax_'+key,title=title,sec='trunk') for key,title in [
    ('spine','Грудные позвонки'),('ribs','Рёбра'),('sternum','Грудина')]]
bone_groups.append(dict(id='b_soft_thorax',title='Рёберные хрящи · контекст',sec='trunk'))
bones={}
for key in manifest.BONES:
    record=deepcopy(BONES[key])
    sub='spine' if key.startswith('thoracic_') else 'ribs' if key.startswith('rib_') else 'sternum'
    record.update(g='thorax_'+sub,sub=sub,v='antmed' if key.endswith('_left') else 'antlat',termScopeNote=APPLICABILITY_NOTE)
    bones[key]=record
for side in ('right','left'):
    record=deepcopy(THORAX_SOFT['cartilage'])
    record.update(ru='Рёберные хрящи · '+('справа' if side=='right' else 'слева'),
        g='b_soft_thorax',sub='ribs',v='ant')
    bones['thorax_costal_cartilages_'+side]=record
muscles={}
for base,source in MUSCLE_TEMPLATES.items():
    for side in ('right','left') if base in SIDED_TEMPLATES else (None,):
        key=base+'_'+side if side else base
        record=deepcopy(source)
        if side:
            record['ru']+=' · '+('справа' if side=='right' else 'слева')
            if side=='left':record['v']={'lat':'med','antlat':'antmed','postlat':'medpost'}.get(record.get('v'),record.get('v','ant'))
        record['noModel']=key not in manifest.MUSCLES
        available={part for _,part in manifest.MUSCLES.get(key,[])}
        for part,data in record.get('parts',{}).items():data['noModel']=part not in available
        if record['noModel']:
            record['contextTargets']={'thorax_subcostales':['rib_10_right','rib_10_left'],
                'thorax_intertransversarii_thoracis':['thoracic_10'],
                'thorax_sternalis':['sternum']}[key]
        muscles[key]=record
assert set(manifest.MUSCLES)<=set(muscles)
assert len(muscles)==43 and sum(not m['noModel'] for m in muscles.values())==40
assert all(m['g'] in {g['id'] for g in groups} for m in muscles.values())
assert all(part in muscles[key].get('parts',{}) for key,parts in manifest.MUSCLES.items() for _,part in parts if part)
text='/* Generated by scripts/make_thorax_data.py. */\n(function(A){\n'
for key,value in [('groups',groups),('boneGroups',bone_groups)]:text+='A.'+key+'.push(...'+json.dumps(value,ensure_ascii=False)+');\n'
for key,value in [('muscles',muscles),('bones',bones)]:text+='Object.assign(A.'+key+','+json.dumps(value,ensure_ascii=False,indent=2)+');\n'
text+='})(window.ATLAS);\n'
(ROOT/'site/data-thorax.js').write_text(text,encoding='utf-8')
print(len(manifest.BONES),'bones;',len(muscles),'muscle cards;',len(manifest.MUSCLES),'modeled source groups;',len(manifest.OTHER),'cartilage objects')
