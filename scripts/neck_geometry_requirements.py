"""Addressed requirements for unlocated neck structures, never coordinate synthesis.

The explicit rules refer to anatomical entities reviewed in neck_terms and
neck_stage5_review. They do not establish specimen-specific localization.
"""
REPORT = 'research/stage5-neck-batch2-report-2026-10-17.md'

def requirements(record):
    code, bone = record.get('c'), record['b']
    related = []
    if record['id'].startswith('shared_neck_intervertebral_'):
        upper, lower = [r['bone'] for r in record['relations']]
        related = [f'neck_{upper}_A02_2_01_010', f'neck_{lower}_A02_2_01_009']
        need = 'Разметить просвет и костные границы отдельно справа и слева на собранной паре позвонков. Для полного отверстия нужны согласованные с тем же образцом диск, суставная капсула и связочные границы; точка вырезки не является центром отверстия.'
        available = 'Обе целые костные сетки; отдельной принятой геометрии отверстия и его мягкотканных стенок нет.'
    elif code == 'A02.2.01.004':
        need = 'Установить возраст и стадию сращения эпифиза на исходном образце; нужны исходные изображения/сегментация зоны окостенения. Наружная взрослая сетка тела не определяет границы эпифиза.'
        available = 'Сетка тела позвонка без отдельной возрастной сегментации эпифиза.'
        related = [f'neck_{bone}_A02_2_01_002']
    elif code in ('A02.2.01.009', 'A02.2.01.010'):
        need = 'Независимо разметить обе вырезки, их открытые края и связь с соответствующим межпозвоночным уровнем. Нужны боковые/косые виды и анатомическая приёмка; маркер ножки или дуги не задаёт выемку.'
        available = 'Целая сетка позвонка; выделенной вырезки нет.'
        related = [f'neck_{bone}_A02_2_02_108'] if bone == 'atlas' else [f'neck_{bone}_A02_2_01_006']
    elif code == 'A02.2.02.106':
        need = 'Разметить суставную площадку на задней стороне передней дуги C1, её края и обе поверхности сочленения отдельно. Координату зуба C2 не переносить.'
        available = 'Сетка передней дуги C1; отдельной маски суставной площадки нет.'
        related = ['neck_atlas_A02_2_02_105', 'neck_axis_A02_2_02_204']
    elif code == 'A02.2.02.109':
        need = 'Проследить ход и ширину борозды позвоночной артерии на верхней стороне задней дуги C1 отдельно справа и слева; нужны согласованные верхние/задние/косые виды и принятая полилиния.'
        available = 'Сетка задней дуги C1, без размеченной борозды.'
        related = ['neck_atlas_A02_2_02_108']
    elif code == 'A02.2.02.110':
        need = 'Сначала установить наличие полного/неполного костного мостика на каждой стороне данного образца по исходным изображениям и сетке. Только при наличии размечать проход; вариант не обязан иметь модель у каждого человека.'
        available = 'Сетка C1; вариантный канал на ней не подтверждён.'
        related = ['neck_atlas_A02_2_02_109']
    elif code in ('A02.2.02.004', 'A02.2.02.005', 'A02.2.02.006'):
        need = 'Разметить бугорок и переход в поперечный отросток независимо с обеих сторон. Координата всего отростка не доказывает положение бугорка.'
        if bone == 'cervical_7' and code.endswith('.004'):
            need += ' Для C7 сначала подтвердить наличие/рудиментарность переднего бугорка на данном образце.'
        if bone == 'cervical_6' and code in ('A02.2.02.004', 'A02.2.02.005'):
            need += ' Передний и сонный бугорок C6 — одно образование: будущая разметка должна быть общей для двух терминологических ID.'
        available = 'Целый поперечный отросток; отдельной принятой разметки бугорка нет.'
        related = [f'neck_{bone}_A02_2_01_013']
    elif code == 'A02.2.02.007':
        need = 'Проследить борозду спинномозгового нерва между бугорками с обеих сторон; нужны размеченные ход и края, без переноса координат отростка. На C7 проверить выраженность борозды.'
        available = 'Целый поперечный отросток без принятой полилинии борозды.'
        related = [f'neck_{bone}_A02_2_02_004', f'neck_{bone}_A02_2_02_006']
    elif record['id'].startswith('extra_atlas_transverse_ligament_tubercle_'):
        need = 'На указанной стороне выделить медиальный бугорок и основание на латеральной массе C1. Нужны медиальные/косые виды и анатомическая приёмка; маркер массы не заменяет бугорок.'
        available = 'Целая латеральная масса C1; отдельного принятого меша бугорка нет.'
    elif record['id'].startswith('extra_hyoid_body_surface_'):
        need = 'Разметить границы данной поверхности тела подъязычной кости и переходы к рогам/краям по переднему, заднему и косому видам. Маркер тела — только контекст, не доказательство всей площади.'
        available = 'Целое тело подъязычной кости; отдельной поверхностной маски нет.'
    elif record['id'].startswith('extra_hyoid_body_border_'):
        need = 'Выделить соответствующий край именно тела подъязычной кости, с концами у переходов к рогам; нужны принятая полилиния и несколько согласованных видов. Весь наружный контур кости не равен этому краю.'
        available = 'Целое тело подъязычной кости; принятого контура края нет.'
    elif record['id'] == 'extra_axis_dens_neck':
        need = 'Выделить суженную часть зуба C2 и переход к телу на этом образце. Нужны анатомически принятые границы области по нескольким видам/исходным изображениям; средние размеры из статьи не переносить.'
        available = 'Целый зуб C2; отдельной разметки его шейки нет.'
    else:
        raise ValueError('Unreviewed unlocated neck entity: '+record['id'])
    return dict(representation=record['geometryKind'], available=available,
                neededEvidence=need, coordinateReuse=False, report=REPORT), related

def annotate_unlocated(record):
    if record.get('p'):
        return record
    req, related = requirements(record)
    record['geometryRequirements'] = req
    record['relatedLandmarks'] = list(dict.fromkeys(record.get('relatedLandmarks', []) + related))
    record['modelNote'] += ' Для отображения: ' + req['neededEvidence']
    return record
