for key, parts in P.items():
    start = src.index(f"\n    {key}: {{")
    end = src.index("\n    },", start)
    block = src[start:end]
    m = re.search(r"\n      parts: \{[^\n]*\},", block)
    assert m, key
    lines = ["\n      parts: {"]
    items = list(parts.items())
    for n, (pk, pv) in enumerate(items):
        lines.append(f"\n        {pk}: {json.dumps(pv, ensure_ascii=False)}{',' if n < len(items) - 1 else ''}")
    lines.append("\n      },")
    block = block[:m.start()] + "".join(lines) + block[m.end():]
    if key in NOTES:
        if re.search(r'\n      note: "[^"]*"', block):
            block = re.sub(r'\n      note: "[^"]*"', "\n      note: " + json.dumps(NOTES[key], ensure_ascii=False), block)
        else:
            block = block.rstrip() + ",\n      note: " + json.dumps(NOTES[key], ensure_ascii=False)
    src = src[:start] + block + src[end:]

