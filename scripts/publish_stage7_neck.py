"""Publish only the individually admitted right subset; all trial data retained."""
import hashlib, json, pathlib, sys
import numpy as np
import trimesh
from neck_stage7_admission import cards

ROOT = pathlib.Path(__file__).resolve().parents[1]
run = pathlib.Path(sys.argv[1])
records = json.loads((run/'derivatives.json').read_text())
record = next(r for r in records if r['id']=='interspinales-candidate-right')
source = ROOT/record['file']
assert hashlib.sha256(source.read_bytes()).hexdigest()==record['sha256']
mesh = trimesh.load(source,force='mesh',process=False)
id = 'interspinales_cervicis_right'
scene = trimesh.Scene();scene.add_geometry(mesh,node_name='m|'+id+'|',geom_name='m|'+id+'|')
out = ROOT/'site/models/bodyparts3d-3.0/neck-stage7';out.mkdir(parents=True,exist_ok=True)
target=out/(id+'.glb');data=scene.export(file_type='glb')
if target.exists(): assert target.read_bytes()==data, 'Different derivative already exists'
else: target.write_bytes(data)
back=trimesh.load(target,force='mesh',process=False)
assert np.array_equal(back.triangles,mesh.triangles)
assert len(back.faces)==2800
provenance={**record,'id':id,'file':target.relative_to(ROOT).as_posix(),
            'sha256':hashlib.sha256(data).hexdigest(),'admission':'educational_limited_partial',
            'coverage':'Five right components C2-C3 through C6-C7; C7-T1 missing; C1-C2-adjacent fragments excluded.',
            'evidenceRun':run.as_posix(),'anatomicalAccuracy':'Exact attachment areas and all muscle contacts unaccepted; no external expert acceptance.',
            'decision':'Source FMA identity + independent typical anatomy + component endpoint review + Blender views. No admission based on distance alone.'}
(out/'provenance.json').write_text(json.dumps(provenance,ensure_ascii=False,indent=2),encoding='utf8')
text='/* Generated by scripts/publish_stage7_neck.py; edit neck_stage7_admission.py. */\n(function(A){\nconst cards='+json.dumps(cards(),ensure_ascii=False,indent=2)+';\nfor(const id of Object.keys(cards)){if(A.muscles[id])throw new Error("Duplicate muscle ID: "+id);}\nObject.assign(A.muscles,cards);\nA.supplementalMuscles={...(A.supplementalMuscles||{}),neck:[...(A.supplementalMuscles?.neck||[]),"interspinales_cervicis_right"]};\n})(window.ATLAS);\n'
(ROOT/'site/data-neck-recovery.js').write_text(text,encoding='utf8')
with (run/'neck-published.json').open('x',encoding='utf8') as f:json.dump(provenance,f,ensure_ascii=False,indent=2)
print(json.dumps({'cards':2,'models':1,'triangles':2800}))
