"""Publish admitted derivatives only, with exact triangle coordinates retained."""
import hashlib,json,pathlib,sys
import numpy as np
import trimesh
from geometry_export_guard import bone_mesh
from muscle_stage7_sources import SOURCES,cards,ROOT_URL
ROOT=pathlib.Path(__file__).resolve().parents[1];run=pathlib.Path(sys.argv[1])
out=ROOT/'site/models/bodyparts3d-3.0/muscles-stage7';out.mkdir(parents=True,exist_ok=True)
R=np.array([[1,0,0],[0,0,1],[0,-1,0]])
records=[]
for id,s in SOURCES.items():
 source=ROOT/'research/cache/stage7-sources'/f"{s['fma']}.obj";sha=hashlib.sha256(source.read_bytes()).hexdigest()
 assert sha==s['sha256'],'Source hash changed'
 m=trimesh.load(source,force='mesh',process=False);vertices=m.vertices@R.T/1000
 # Exact welding improves smooth normals; no rounding, remeshing or triangle removal.
 mesh=bone_mesh(vertices,m.faces)
 scene=trimesh.Scene();scene.add_geometry(mesh,node_name='m|'+id+'|',geom_name='m|'+id+'|')
 data=scene.export(file_type='glb');target=out/(id+'.glb')
 if target.exists():assert target.read_bytes()==data,'Refuse to overwrite a different derivative'
 else:target.write_bytes(data)
 back=trimesh.load(target,force='mesh',process=False)
 assert len(back.faces)==len(m.faces)
 assert np.array_equal(back.triangles,vertices[m.faces].astype(np.float32).astype(float))
 assert np.isfinite(back.vertex_normals).all()
 records.append(dict(id=id,source=s,sourceURL=ROOT_URL,derivedFile=target.relative_to(ROOT).as_posix(),triangles=len(m.faces),sha256=hashlib.sha256(data).hexdigest(),maxVertexErrorM=float(np.max(np.abs(back.triangles-vertices[m.faces]))),method='Exact coordinate welding, stable smooth normals, mm Z-up to m Y-up; all triangle corners/order preserved. No mirroring or fitting.',admission='educational_limited'))
with(run/'puborectalis-export.json').open('x',encoding='utf8')as f:json.dump(records,f,ensure_ascii=False,indent=2)
(out/'provenance.json').write_text(json.dumps(records,ensure_ascii=False,indent=2),encoding='utf8')
text='/* Generated by scripts/publish_stage7_puborectalis.py; edit muscle_stage7_sources.py. */\n(function(A){\nconst cards='+json.dumps(cards(),ensure_ascii=False,indent=2)+';\nfor(const id of Object.keys(cards)){if(A.muscles[id])throw new Error("Duplicate muscle ID: "+id);}\nObject.assign(A.muscles,cards);\nA.supplementalMuscles={...(A.supplementalMuscles||{}),leg:Object.keys(cards)};\nA.muscles.levator_ani.relatedMuscles=Object.keys(cards);\nA.muscles.levator_ani.note += " Здесь показаны правые лобково-копчиковая и подвздошно-копчиковая мышцы. Лобково-прямокишечные компоненты открываются отдельными связанными карточками.";\n})(window.ATLAS);\n'
(ROOT/'site/data-muscle-recovery.js').write_text(text,encoding='utf8')
print(json.dumps({'published':len(records),'triangles':[r['triangles']for r in records]}))
